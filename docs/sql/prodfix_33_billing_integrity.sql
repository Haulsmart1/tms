-- ===========================================================================
-- STEP 3: at most one succeeded, non-zero charge of each kind per period.
-- ===========================================================================
--
-- The database backstop for BILL2-2. Zero-amount settled rows are excluded:
-- they record "nothing was owed" and a period can legitimately carry more than
-- one (a declined attempt that later recomputes to zero). Skipped with a notice
-- if duplicates already exist, because those are double charges to refund by
-- hand, and creating the index would fail the whole file.
do $$
begin
  if exists (
    select 1 from public.period_charges
    where status = 'succeeded' and gross_pence > 0
    group by billing_period_id, kind having count(*) > 1
  ) then
    raise notice 'prodfix_33: DUPLICATE succeeded period charges exist; index NOT created. Reconcile these first: select billing_period_id, kind, count(*) from public.period_charges where status = ''succeeded'' and gross_pence > 0 group by 1, 2 having count(*) > 1;';
  else
    execute 'create unique index if not exists period_charges_one_success
               on public.period_charges (billing_period_id, kind)
               where status = ''succeeded'' and gross_pence > 0';
  end if;
end $$;

