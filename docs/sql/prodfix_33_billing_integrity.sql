-- ===========================================================================
-- STEP 1: claim a period for collection (BILL2-2).
-- ===========================================================================
--
-- Computing a period was already claimed (open -> closing). Collecting one that
-- was already closed or failed was not: two runs holding a stale snapshot both
-- charged it, the second under a NEW attempt number, which is a new idempotency
-- key, which Square treats as a new payment.
--
-- The claim is a conditional update on (status, attempt_count, marker), so it
-- succeeds for exactly one caller. A claim older than p_stale_minutes is
-- considered abandoned by a crashed run and may be taken over; that is safe
-- because the charge path replays a pending row under its original key rather
-- than minting a new one. The collecting run clears the marker when it writes
-- the outcome.
alter table public.billing_periods
  add column if not exists collecting_since timestamptz;

comment on column public.billing_periods.collecting_since is
  'Set while a run is charging this period. Cleared when the outcome is written. See claim_billing_period_collection.';

create or replace function public.claim_billing_period_collection(
  p_period_id uuid,
  p_expected_attempt_count int,
  p_stale_minutes int
)
returns boolean
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_id uuid;
begin
  update public.billing_periods
     set collecting_since = now()
   where id = p_period_id
     and status in ('closed', 'failed')
     and attempt_count = p_expected_attempt_count
     and (
       collecting_since is null
       or collecting_since < now() - make_interval(mins => greatest(coalesce(p_stale_minutes, 15), 1))
     )
  returning id into v_id;

  return v_id is not null;
end $$;

revoke all on function public.claim_billing_period_collection(uuid, int, int)
  from public, anon, authenticated;
grant execute on function public.claim_billing_period_collection(uuid, int, int)
  to service_role;

