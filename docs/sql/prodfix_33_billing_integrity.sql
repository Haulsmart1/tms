-- Same signature as billing_04, so existing grants carry over under
-- `create or replace`; they are restated below anyway.
--
-- CHANGED: a conflict with a PENDING row for the same attempt now settles it
-- (status, payment id, receipt, failure code). The amounts stored on the
-- pending row are kept: they are what the idempotency key bought. A conflict
-- with an already settled row still changes nothing, which keeps the replay
-- after a crash idempotent. Coverage is written only when the row for this
-- attempt is succeeded after the upsert, so a late caller cannot write
-- coverage against a row that settled as failed.
create or replace function public.record_cycle_charge(
  p_company_id uuid,
  p_cycle_date date,
  p_attempt int,
  p_vehicle_count int,
  p_net_pence bigint,
  p_vat_pence bigint,
  p_gross_pence bigint,
  p_vat_rate numeric,
  p_currency text,
  p_square_payment_id text,
  p_receipt_url text,
  p_status text,
  p_failure_code text,
  p_vehicle_ids uuid[]
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  insert into public.platform_charges (
    company_id, cycle_date, attempt, vehicle_count,
    net_pence, vat_pence, gross_pence, vat_rate, currency,
    square_payment_id, receipt_url, status, failure_code
  )
  values (
    p_company_id, p_cycle_date, p_attempt, p_vehicle_count,
    p_net_pence, p_vat_pence, p_gross_pence, p_vat_rate, p_currency,
    p_square_payment_id, p_receipt_url, p_status, p_failure_code
  )
  on conflict (company_id, cycle_date, attempt) do update
    set status = excluded.status,
        square_payment_id = excluded.square_payment_id,
        receipt_url = excluded.receipt_url,
        failure_code = excluded.failure_code
    where public.platform_charges.status = 'pending';

  if p_status = 'succeeded' and exists (
    select 1 from public.platform_charges
    where company_id = p_company_id
      and cycle_date = p_cycle_date
      and attempt = p_attempt
      and status = 'succeeded'
  ) then
    insert into public.vehicle_cycle_coverage (company_id, cycle_date, vehicle_id)
    select p_company_id, p_cycle_date, vid
    from unnest(coalesce(p_vehicle_ids, '{}'::uuid[])) as vid
    on conflict (company_id, cycle_date, vehicle_id) do nothing;
  end if;
end $$;

