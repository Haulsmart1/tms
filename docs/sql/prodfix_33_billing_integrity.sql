-- ===========================================================================
-- STEP 6: refuse to open a period the spec says must not exist.
-- ===========================================================================
--
-- The spec relies on an ensure_open_billing_period function "that refuses to
-- open a new period while one is failed" and "opens no successor" for a
-- cancelled company. It was never created (BILL2-20), and those missing guards
-- were BILL2-1 (a cancelled company billed every 28 days) and BILL2-6 (a
-- failing company opened a fresh period). The application now checks both;
-- this is the layer that holds if a code path forgets.
--
-- Only an OPENING is judged: an insert of an open period, or an update that
-- moves a period INTO open. Updates to an already-open period (prepaid, a
-- shortened end on cancellation) pass untouched.
--
-- Invoker rights: it reads company_billing and billing_periods, which the
-- service role can read, and it only raises.
create or replace function public.guard_billing_period_open()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_status text;
begin
  if new.status::text <> 'open' then
    return new;
  end if;
  if tg_op = 'UPDATE' and old.status::text = 'open' then
    return new;
  end if;

  select cb.status into v_status
  from public.company_billing cb
  where cb.company_id = new.company_id;

  if v_status is distinct from 'active' then
    raise exception 'A billing period cannot be opened for company % while its billing status is %.',
        new.company_id, coalesce(v_status, 'missing')
      using errcode = 'BIL01', hint = 'billing_period_company_not_active';
  end if;

  if exists (
    select 1 from public.billing_periods p
    where p.company_id = new.company_id
      and p.id <> new.id
      and p.status::text in ('closing', 'closed', 'failed')
  ) then
    raise exception 'A billing period cannot be opened for company % while an earlier period is unpaid.',
        new.company_id
      using errcode = 'BIL01', hint = 'billing_period_unpaid';
  end if;

  return new;
end $$;

revoke all on function public.guard_billing_period_open() from public, anon, authenticated;

drop trigger if exists guard_billing_period_open on public.billing_periods;
create trigger guard_billing_period_open
  before insert or update of status on public.billing_periods
  for each row execute function public.guard_billing_period_open();

